import { chromium } from '/Users/davidmiranda/Documents/GitHub/hyper/hyper-morph/node_modules/playwright/index.mjs';
const [,, out, w, h, setup, waitMs = '4000'] = process.argv;
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: +w, height: +h }, deviceScaleFactor: 2 });
await page.addInitScript((seed) => { localStorage.clear(); let a = seed >>> 0; Math.random = () => { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }, +(process.env.SEED || 7));
page.on('console', (m) => { if (m.type() === 'error' || m.text().startsWith('[shot]')) console.log(m.text()); });
await page.goto('http://localhost:5231/');
await page.waitForFunction(() => window.game?.renderer);
await page.keyboard.press('Space');
await page.waitForTimeout(500);
if (setup) await page.evaluate(setup);
await page.waitForTimeout(+waitMs);
await page.addStyleTag({ content: '#hud, .overlay, #toast, [id*=toast] { display: none !important; }' });
await page.waitForTimeout(100);
await page.screenshot({ path: out });
await browser.close();
